"""Runtime localization and bundled Simplified Chinese pixel-font support."""

from __future__ import annotations

from pathlib import Path
import re
import sys

import pygame


_language: str = "en"
_font_cache: dict[int, pygame.font.Font] = {}


def set_language(language: str) -> None:
    global _language
    _language = "zh_hans" if language == "zh_hans" else "en"


def get_language() -> str:
    return _language


def is_chinese() -> bool:
    return _language == "zh_hans"


def resource_path(*parts: str) -> Path:
    root = Path(getattr(sys, "_MEIPASS", Path(__file__).resolve().parent.parent))
    return root.joinpath(*parts)


def get_chinese_font(size: int = 12) -> pygame.font.Font:
    size = max(8, int(size))
    if size not in _font_cache:
        path = resource_path(
            "assets", "fonts", "fusion-pixel-12px-proportional-zh_hans.ttf"
        )
        _font_cache[size] = pygame.font.Font(str(path), size)
    return _font_cache[size]


