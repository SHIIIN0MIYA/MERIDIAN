def _format_dynamic(text: str) -> str:
    patterns = (
        (r"^SCORE (\d+)$", r"得分 \1"),
        (r"^BEST (\d+)$", r"最高 \1"),
        (r"^LINES (\d+)\s+LEVEL (\d+)$", r"消行 \1　等级 \2"),
        (r"^TIME (.+)$", r"时间 \1"),
        (r"^Current: (.+)$", r"当前：\1"),
        (r"^OPEN (\d+)$", r"已翻开 \1"),
        (r"^CHAPTER (\d+)$", r"章节 \1"),
        (r"^CHAPTER (\d+) // (.+)$", r"章节 \1 // \2"),
        (r"^(.+) / MISSION$", r"\1 / 任务"),
        (r"^(.+) / BOSS$", r"\1 / Boss"),
        (r"^OBJECTIVE: DESTROY (.+)$", r"任务目标：摧毁 \1"),
        (r"^(.+) // PHASE (\d+)$", r"\1 // 阶段 \2"),
        (r"^(.+) // PHASE (\d+) // ARMOR SHIFT$", r"\1 // 阶段 \2 // 装甲切换"),
        (r"^WARNING // (.+) // PHASE (\d+)$", r"警报 // \1 // 阶段 \2"),
        (r"^ALERT: HOSTILE COMMAND FRAME (.+) CONFIRMED\.$", r"警报：确认敌方指挥机体 \1。"),
        (r"^COMMAND: CHAPTER (\d+) FLIGHT WINDOW IS OPEN\.$", r"指挥部：第 \1 章飞行窗口已开启。"),
        (r"^ARCHIVE (\d+) // (.+)$", r"档案 \1 // \2"),
        (r"^COMMAND FRAME: (.+)$", r"指挥机体：\1"),
        (r"^A / D  RECORD (\d+) / (\d+)\s+ESC  RETURN$", r"A / D：档案 \1 / \2　ESC：返回"),
        (r"^(.+)\s+ESC  MENU$", r"\1　ESC：菜单"),
        (r"^(.+)  PLAY (.+)$", r"\1　游玩时间 \2"),
        (r"^CHARGE (\d+)%$", r"充能 \1%"),
        (r"^DESTROYED (\d+) / (\d+)$", r"击破 \1 / \2"),
        (r"^GRAZES (\d+)\s+HULL (\d+) / 5$", r"擦弹 \1　耐久 \2 / 5"),
        (r"^COMBO\s+(\d+)$", r"连击 \1"),
        (r"^GRAZE\s+(\d+)$", r"擦弹 \1"),
        (r"^MULTI\s+x(.+)$", r"倍率 x\1"),
        (r"^COMPLETE (\d+) / (\d+)\s+(\d+)%$", r"完成 \1 / \2　\3%"),
        (r"^(.+) / LOCKED$", r"\1 / 未解锁"),
        (r"^UNLOCKED (\d+) / (\d+)$", r"已解锁 \1 / \2"),
        (r"^(.+) WINS$", r"\1胜利"),
        (r"^(.+)'S TURN$", r"轮到\1"),
        (r"^FPS (.+)$", r"帧率 \1"),
        (r"^INDEX (\d+)$", r"指数 \1"),
        (r"^UNLOCKED (\d+) / (\d+)$", r"已解锁 \1 / \2"),
    )
    for pattern, replacement in patterns:
        if re.match(pattern, text):
            return re.sub(pattern, replacement, text)
    return text


def translate(text: str) -> str:
    if not is_chinese() or not isinstance(text, str):
        return text
    translated = ZH.get(text)
    if translated is not None:
        return translated
    return _format_dynamic(text)


def contains_chinese(text: str) -> bool:
    return bool(re.search(r"[\u3400-\u9fff]", text))


